    add_body_text(doc, 'L_Focal-EIoU = (1 - IoU)^γ · [1 - IoU + ρ²(b, b_gt) / c² + ρ²(w, w_gt) / Cw² + ρ²(h, h_gt) / Ch²]')

    add_body_text(doc, '其中，聚焦因子(1-IoU)^γ在IoU接近1时（高质量回归）趋近于0，极大地降低了此类样本的损失；在IoU较小时（低质量回归）保持在较高水平，使这些困难样本获得充足的优化信号。γ参数控制聚焦的强度：γ=0退化为标准EIoU，γ越大聚焦效应越强。本文取γ=0.5，这是一个相对温和的设置，在保持训练稳定性的前提下提供有意义的聚焦效果。')

    add_body_text(doc, '在代码实现层面，Focal-EIoU仅需在BboxLoss类的forward方法中增加一行focal_weight的计算：focal_weight = (1.0 - iou.detach()).pow(0.5)。其中detach()操作用于阻断focal_weight对梯度计算图的影响，使其纯粹作为损失的比例缩放因子，不参与反向传播梯度（避免对IoU的二次导数）。focal_weight与原有加权系数weight相乘后作用于(1-IoU)项，实现聚焦式的边界框回归损失。')

    add_body_text(doc, 'Focal-EIoU对分类损失和置信度损失不产生直接影响，其优化效果集中体现在边界框定位精度的提升上，特别有利于IoU容易剧烈波动的小目标样本。消融实验中将验证Focal-EIoU对小目标mAP的独立贡献。')

